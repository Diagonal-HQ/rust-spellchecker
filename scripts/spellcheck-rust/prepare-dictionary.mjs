#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repositoryRoot = resolve(import.meta.dirname, '../..');
const output = resolve(
  repositoryRoot,
  process.argv[2] ?? 'scripts/spellcheck-rust/native/target/cspell-lexicon.txt',
);
const cspellModuleRoot = process.env.CSPELL_MODULE_ROOT
  ? resolve(process.env.CSPELL_MODULE_ROOT)
  : repositoryRoot;
const cspellEntry = resolve(cspellModuleRoot, 'node_modules/cspell-lib/dist/index.js');
const cspell = await import(pathToFileURL(cspellEntry));
const cspellPackage = JSON.parse(
  await readFile(resolve(cspellModuleRoot, 'node_modules/cspell/package.json'), 'utf8'),
);
const configPath = resolve(repositoryRoot, 'cspell.json');
const packageLockPath = resolve(repositoryRoot, 'package-lock.json');
const cspellInstallLockPath = resolve(cspellModuleRoot, 'package-lock.json');
const scriptPath = fileURLToPath(import.meta.url);
const configBytes = await readFile(configPath);
const packageLockBytes = await readFile(packageLockPath);
const cspellInstallLockBytes = await readFile(cspellInstallLockPath);
const scriptBytes = await readFile(scriptPath);
const userSettings = await cspell.readSettings(configPath);
const languageIds = ['typescriptreact', 'php', 'html', 'markdown'];
const words = new Set();
const compoundWords = new Set();
const dictionaries = new Set();

for (const languageId of languageIds) {
  const { settings } = await cspell.determineFinalDocumentSettings(
    {
      uri: pathToFileURL(resolve(repositoryRoot, `dictionary-probe.${languageId}`)).href,
      text: '',
      languageId,
    },
    userSettings,
  );
  const collection = await cspell.getDictionary(settings);

  for (const dictionary of collection.dictionaries) {
    const trie = dictionary.trie ?? dictionary.dict?.trie;
    if (!trie) continue;
    dictionaries.add(dictionary.name);
    for (const word of trie.words()) {
      if (dictionary.name === 'coding-compound-terms' && word.includes('+')) {
        compoundWords.add(word.toLocaleLowerCase('en-US'));
      }
      if (collection.has(word)) {
        words.add(word.toLocaleLowerCase('en-US').replaceAll(/[’`]/gu, "'"));
      }
    }
  }
}

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const body = [
  ...[...compoundWords]
    .sort((a, b) => a.localeCompare(b, 'en-US'))
    .map((word) => `@compound\t${word}`),
  ...[...words].sort((a, b) => a.localeCompare(b, 'en-US')),
  '',
].join('\n');
const lines = [
  '# Generated by scripts/spellcheck-rust/prepare-dictionary.mjs; do not commit.',
  '# format=2',
  `# cspell=${cspellPackage.version}`,
  `# cspell.json.sha256=${sha256(configBytes)}`,
  `# package-lock.json.sha256=${sha256(packageLockBytes)}`,
  `# cspell-install.package-lock.sha256=${sha256(cspellInstallLockBytes)}`,
  `# prepare-dictionary.mjs.sha256=${sha256(scriptBytes)}`,
  `# languageIds=${languageIds.join(',')}`,
  `# dictionaries=${[...dictionaries].sort().join(',')}`,
  `# entries.sha256=${sha256(body)}`,
  body,
];

await mkdir(dirname(output), { recursive: true });
await writeFile(output, lines.join('\n'));
console.log(
  `Wrote ${words.size} accepted words from CSpell ${cspellPackage.version} to ${output}`,
);
